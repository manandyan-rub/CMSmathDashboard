const dictionaries: Record<string, Messages> = { en, hy, ru, fr };

export function useCmsI18n(locale: Ref<string>) {
    const messages = computed(() => dictionaries[locale.value] ?? en);

    function t(key: string, replacements: Record<string, string | number> = {}): string {
        let message = messages.value[key] ?? en[key] ?? key;
        Object.entries(replacements).forEach(([name, value]) => {
            message = message.replace(`{${name}}`, String(value));
        });

        return message;
    }

    return { t };
}
